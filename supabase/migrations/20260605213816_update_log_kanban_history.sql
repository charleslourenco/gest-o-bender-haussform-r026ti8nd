CREATE OR REPLACE FUNCTION public.log_kanban_history()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $function$
DECLARE
  status_map jsonb := '{"iniciar": "Iniciar", "aguardando_liberacao": "Aguardando liberação", "medida_fina": "Medida Fina", "reuniao_analise": "Reunião de Análise", "caderno_tecnico": "Caderno Técnico", "alteracao_projeto": "Alteração de projeto", "lista_materiais": "Lista de Materiais", "aguardando_plano_corte": "Aguardando Plano de Corte", "router": "Router", "coladeira": "Coladeira", "bancada": "Bancada", "embalagem": "Embalagem", "expedicao": "Expedição", "aguardando_agenda": "Aguardando Agenda", "transporte": "Transporte", "montagem": "Montagem", "item_terceirizado": "Item Terceirizado", "pendencia": "Pendência", "assistencia": "Assistência", "concluido": "Concluído"}'::jsonb;
  human_status text;
BEGIN
  IF NEW.status_analise IS DISTINCT FROM OLD.status_analise THEN
    INSERT INTO public.kanban_historico (card_id, status_anterior, status_novo, usuario_id)
    VALUES (NEW.id, OLD.status_analise, NEW.status_analise, auth.uid());
    
    -- Automatic timeline events generated by the system reflecting Otto's management
    IF NEW.cliente_id IS NOT NULL THEN
      human_status := COALESCE(status_map->>NEW.status_analise, NEW.status_analise);
      INSERT INTO public.timeline_eventos (cliente_id, usuario_nome, acao, icone)
      VALUES (NEW.cliente_id, 'Seu Otto', 'Moveu o ambiente [' || NEW.nome_produto || '] para a etapa: ' || human_status, '⚙️');
    END IF;
  END IF;
  RETURN NEW;
END;
$function$;
